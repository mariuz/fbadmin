#!/usr/bin/env python3
"""Regenerate backend/fbadmin/upgrade/keywords_data.py (the upgrade assistant's keyword lists).

Sources, per Firebird version:
  3.0  the Firebird source code (tag v3.0.12): every word token in src/common/keywords.cpp is a
       keyword; it is reserved unless it appears in the ``non_reserved_word`` rule of src/dsql/parse.y.
  4.0  the Firebird source code (tag v4.0.5): src/common/keywords.cpp, whose third column is
       ``nonReserved``. Firebird 4 has no RDB$KEYWORDS table (it arrived in Firebird 5).
  5.0  RDB$KEYWORDS of a running Firebird 5 server (default 127.0.0.1:3050).
  6.0  RDB$KEYWORDS of a running Firebird 6 snapshot server (default 127.0.0.1:3056).

Usage: python scripts/gen-upgrade-keywords.py [--fb5 HOST:PORT] [--fb6 HOST:PORT] [--password PW]
A server (or GitHub) that cannot be reached keeps the list already in the data file.
"""

from __future__ import annotations

import argparse
import re
import sys
import urllib.request
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "backend" / "fbadmin" / "upgrade" / "keywords_data.py"
RAW = "https://raw.githubusercontent.com/FirebirdSQL/firebird/{tag}/{path}"
WORD = re.compile(r"^[A-Z][A-Z0-9_$]*$")


def fetch(tag: str, path: str) -> str:
    with urllib.request.urlopen(RAW.format(tag=tag, path=path), timeout=60) as r:  # noqa: S310 - fixed host
        return r.read().decode("utf-8", "replace")


def tokens(src: str) -> list[tuple[str, str, str]]:
    """(token identifier, keyword text, remaining columns) of each entry in keywords.cpp."""
    out = []
    for m in re.finditer(r'\{\s*(\w+)\s*,\s*"([^"]+)"\s*,([^}]*)\}', src):
        if WORD.match(m.group(2)):
            out.append((m.group(1), m.group(2), m.group(3).strip()))
    return out


def fb3() -> dict:
    kw = tokens(fetch("v3.0.12", "src/common/keywords.cpp"))
    parse = fetch("v3.0.12", "src/dsql/parse.y")
    m = re.search(r"^non_reserved_word\s*\n(.*?)^\s*;", parse, re.S | re.M)
    if not m:
        raise SystemExit("non_reserved_word rule not found in parse.y")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    non_reserved = set(re.findall(r"[:|]\s*(\w+)", body))
    return {"source": "Firebird 3.0.12 source: src/common/keywords.cpp and the non_reserved_word rule "
                      "of src/dsql/parse.y",
            "keywords": sorted({w for _, w, _ in kw}),
            "reserved": sorted({w for tok, w, _ in kw if tok not in non_reserved})}


def fb4() -> dict:
    kw = tokens(fetch("v4.0.5", "src/common/keywords.cpp"))
    return {"source": "Firebird 4.0.5 source: src/common/keywords.cpp (nonReserved column)",
            "keywords": sorted({w for _, w, _ in kw}),
            "reserved": sorted({w for _, w, last in kw if last.split(",")[-1].strip() == "false"})}


def from_server(hostport: str, password: str, version: str) -> dict:
    import firebirdsql

    host, port = hostport.rsplit(":", 1)
    path = f"/var/lib/firebird/data/fbadmin_keywords_{uuid.uuid4().hex[:8]}.fdb"
    conn = firebirdsql.create_database(host=host, port=int(port), database=path, user="SYSDBA", password=password)
    try:
        cur = conn.cursor()
        cur.execute("SELECT rdb$get_context('SYSTEM', 'ENGINE_VERSION') FROM RDB$DATABASE")
        engine = cur.fetchone()[0]
        if not engine.startswith(version.split(".")[0] + "."):
            raise SystemExit(f"{hostport} runs Firebird {engine}, expected {version}")
        cur.execute("SELECT TRIM(RDB$KEYWORD_NAME), RDB$KEYWORD_RESERVED FROM RDB$KEYWORDS")
        rows = [(n, bool(r)) for n, r in cur.fetchall() if WORD.match(n)]
        conn.commit()
    finally:
        conn.drop_database()
    return {"source": f"RDB$KEYWORDS of Firebird {engine}", "keywords": sorted(n for n, _ in rows),
            "reserved": sorted(n for n, r in rows if r)}


def load_existing() -> dict:
    if not OUT.exists():
        return {}
    ns: dict = {}
    exec(compile(OUT.read_text(), str(OUT), "exec"), ns)  # noqa: S102 - our own generated file
    return {v: {k: (sorted(x) if not isinstance(x, str) else x) for k, x in d.items()}
            for v, d in ns["KEYWORDS"].items()}


def _words(words: list[str]) -> str:
    lines, line = [], ""
    for w in sorted(words):
        if line and len(line) + len(w) + 1 > 96:
            lines.append(line)
            line = ""
        line = f"{line} {w}" if line else w
    lines.append(line)
    return "\n".join("        " + ln for ln in lines)


def render(data: dict) -> str:
    out = ['"""Firebird keyword lists per version. GENERATED by scripts/gen-upgrade-keywords.py - do not edit."""',
           "", "KEYWORDS: dict[str, dict] = {"]
    for ver in sorted(data):
        d = data[ver]
        out.append(f'    "{ver}": {{')
        out.append(f'        "source": "{d["source"]}",')
        for key in ("keywords", "reserved"):
            out.append(f'        "{key}": """')
            out.append(_words(d[key]))
            out.append('        """.split(),')
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fb5", default="127.0.0.1:3050")
    ap.add_argument("--fb6", default="127.0.0.1:3056")
    ap.add_argument("--password", default="masterkey")
    a = ap.parse_args()
    data = load_existing()
    for ver, fn in (("3.0", fb3), ("4.0", fb4)):
        try:
            data[ver] = fn()
        except Exception as e:  # noqa: BLE001
            print(f"Firebird {ver} source: {e}; keeping the previous list", file=sys.stderr)
    for ver, hp in (("5.0", a.fb5), ("6.0", a.fb6)):
        try:
            data[ver] = from_server(hp, a.password, ver)
        except Exception as e:  # noqa: BLE001
            print(f"Firebird {ver} at {hp}: {e}; keeping the previous list", file=sys.stderr)
    for ver in sorted(data):
        print(f"{ver}: {len(data[ver]['keywords'])} keywords, {len(data[ver]['reserved'])} reserved")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(data))


if __name__ == "__main__":
    main()

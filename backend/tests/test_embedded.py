@pytest.fixture
def emb(client, monkeypatch, tmp_path_factory):
    why = _why_not()
    if why:
        pytest.skip(why)
    monkeypatch.setenv("FBADMIN_EMBEDDED_DIR", EMBEDDED_DIR)
    # lock files of the embedded engine: one directory for the whole test process
    if not os.environ.get("FIREBIRD_LOCK"):
        os.environ["FIREBIRD_LOCK"] = str(tmp_path_factory.mktemp("fblock"))
    st = client.get("/api/embedded/status").json()
    assert st["available"], st["reason"]
    return client


def create_local(client, path: Path, **kw) -> tuple[str, str]:
    r = client.post("/api/embedded/databases", json={"path": str(path), "create": True, **kw})
    assert r.status_code == 201, r.text
    body = r.json()
    return body["server_id"], body["database"]["id"]


def base(sid, dbid):
    return f"/api/servers/{sid}/databases/{dbid}"


def execute(client, sid, dbid, sql):
    r = client.post(base(sid, dbid) + "/execute", json={"sql": sql})
    assert r.status_code == 200, r.text
    assert r.json()["error"] is None, r.json()["error"]
    return r.json()


def wait_job(client, r, timeout=120):
    assert r.status_code == 202, r.text
    jid = r.json()["id"]
    end = time.time() + timeout
    while time.time() < end:
        j = client.get(f"/api/jobs/{jid}").json()
        if j["status"] != "running":
            assert j["status"] == "finished", "\n".join(j["log"])
            return j
        time.sleep(0.1)
    raise AssertionError("job did not finish")


SCHEMA = """
CREATE TABLE CUSTOMERS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME VARCHAR(60) NOT NULL,
  CITY VARCHAR(40) COLLATE UNICODE_CI,
  BALANCE NUMERIC(12,2) DEFAULT 0,
  CREATED TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  NOTES BLOB SUB_TYPE TEXT
);
CREATE INDEX IX_CUSTOMERS_CITY ON CUSTOMERS (CITY);
CREATE VIEW RICH AS SELECT ID, NAME FROM CUSTOMERS WHERE BALANCE > 100;
SET TERM ^ ;
CREATE PROCEDURE ADD_CUSTOMER (N VARCHAR(60), C VARCHAR(40)) RETURNS (NEW_ID INTEGER) AS
BEGIN
  INSERT INTO CUSTOMERS (NAME, CITY) VALUES (:N, :C) RETURNING ID INTO :NEW_ID;
  SUSPEND;
END^
SET TERM ; ^
COMMIT;
"""


@requires_embedded
def test_local_database_end_to_end(emb, tmp_path):
    client = emb
    path = tmp_path / "data" / "shop.fdb"
    sid, dbid = create_local(client, path, page_size=8192, name="Shop")
    assert path.is_file()

    srv = client.get(f"/api/servers/{sid}").json()
    assert srv["embedded"] is True and srv["name"] == "Local databases" and srv["password_known"]
    assert [d["name"] for d in srv["databases"]] == ["Shop"]
    assert client.post(f"/api/servers/{sid}/connect", json={}).json()["server_version"].count(".") >= 2
    info = client.get(f"/api/servers/{sid}/info").json()
    assert "Firebird" in info["architecture"] or info["architecture"]

    # tree, DDL
    r = client.post(base(sid, dbid) + "/connect")
    assert r.status_code == 200, r.text
    assert r.json()["engine_version"].startswith("5.")
    execute(client, sid, dbid, SCHEMA)
    names = [o["name"] for o in client.get(base(sid, dbid) + "/objects/tables").json()]
    assert names == ["CUSTOMERS"]
    assert [o["name"] for o in client.get(base(sid, dbid) + "/objects/procedures").json()] == ["ADD_CUSTOMER"]
    ddl = client.get(base(sid, dbid) + "/objects/tables/CUSTOMERS/script").json()["sql"]
    assert "CREATE TABLE" in ddl and "UNICODE_CI" in ddl and "IX_CUSTOMERS_CITY" in ddl
    props = client.get(base(sid, dbid) + "/info").json()
    assert props["counts"]

    # data grid: insert, update, read back
    r = client.post(base(sid, dbid) + "/tables/CUSTOMERS/data", json={"inserts": [
        {"values": {"NAME": "Ana", "CITY": "Cluj", "BALANCE": "150.50", "NOTES": "ăîâșț"}},
        {"values": {"NAME": "Bob", "CITY": "cluj", "BALANCE": 20}},
    ]})
    assert r.status_code == 200, r.text
    data = client.get(base(sid, dbid) + "/tables/CUSTOMERS/data").json()
    assert data["primary_key"] == ["ID"] and len(data["rows"]) == 2
    first = dict(zip([c["name"] for c in data["columns"]], data["rows"][0], strict=True))
    assert first["NAME"] == "Ana" and first["NOTES"] == "ăîâșț"
    r = client.post(base(sid, dbid) + "/tables/CUSTOMERS/data",
                    json={"updates": [{"key": {"ID": first["ID"]}, "values": {"BALANCE": 175}}]})
    assert r.status_code == 200, r.text
    assert client.get(base(sid, dbid) + "/tables/CUSTOMERS/count").json()["count"] == 2

    # Query Tool session on the embedded engine
    r = client.post("/api/query/sessions", json={"server_id": sid, "database_id": dbid})
    assert r.status_code == 201, r.text
    qs = r.json()["session_id"]
    q = f"/api/query/sessions/{qs}"
    res = client.post(q + "/execute", json={
        "sql": "SELECT NAME, BALANCE FROM CUSTOMERS WHERE CITY = :city ORDER BY ID;", "params": {"CITY": "CLUJ"},
        "with_plan": True, "with_stats": True}).json()
    assert res["error"] is None, res["error"]
    sel = res["results"][0]
    assert sel["kind"] == "select" and sel["rows"] == [["Ana", "175.00"], ["Bob", "20.00"]] or \
        [r[0] for r in sel["rows"]] == ["Ana", "Bob"]
    assert "CUSTOMERS" in (sel["plan"] or "")
    assert sel["stats"] is not None
    # explicit transaction: rollback undoes, commit keeps
    res = client.post(q + "/execute", json={"sql": "INSERT INTO CUSTOMERS (NAME) VALUES ('Tmp');",
                                            "autocommit": False}).json()
    assert res["error"] is None and res["transaction_open"] is True
    assert client.post(q + "/rollback").json()["transaction_open"] is False
    res = client.post(q + "/execute", json={"sql": "SELECT COUNT(*) FROM CUSTOMERS"}).json()
    assert res["results"][0]["rows"] == [[2]]
    res = client.post(q + "/execute", json={"sql": "SELECT * FROM ADD_CUSTOMER('Cid', 'Iasi');",
                                            "autocommit": False}).json()
    assert res["error"] is None
    client.post(q + "/commit")
    # transaction options (isolation, read-only, statement timeout) through the raw TPB
    r = client.put(q + "/options", json={"isolation": "snapshot", "read_only": True, "statement_timeout": 5000})
    assert r.status_code == 200, r.text
    assert r.json()["isolation"] == "snapshot" and r.json()["statement_timeout"] == 5000
    res = client.post(q + "/execute", json={"sql": "UPDATE CUSTOMERS SET BALANCE = 0"}).json()
    assert res["error"] and "read-only" in res["error"]["message"].lower()
    res = client.post(q + "/execute", json={
        "sql": "SELECT RDB$GET_CONTEXT('SYSTEM','ISOLATION_LEVEL'), RDB$GET_CONTEXT('SYSTEM','READ_ONLY') "
               "FROM RDB$DATABASE"}).json()
    assert res["results"][0]["rows"] == [["SNAPSHOT", "TRUE"]]
    client.put(q + "/options", json={})
    # plan, errors with positions, fetch more
    plan = client.post(q + "/explain", json={"sql": "SELECT * FROM CUSTOMERS WHERE CITY = 'x'"}).json()
    assert "IX_CUSTOMERS_CITY" in plan["plan"] and plan["detailed"]
    res = client.post(q + "/execute", json={"sql": "SELECT 1 FROM RDB$DATABASE;\nSELECT nope FROM CUSTOMERS"}).json()
    assert res["error"] and res["error"]["position"] and res["error"]["position"]["line"] == 2
    res = client.post(q + "/execute", json={
        "sql": "SELECT n FROM (WITH RECURSIVE r(n) AS (SELECT 1 FROM RDB$DATABASE UNION ALL "
               "SELECT n + 1 FROM r WHERE n < 25) SELECT n FROM r)", "max_rows": 10}).json()
    assert res["cursor_open"] and len(res["results"][0]["rows"]) == 10
    more = client.post(q + "/fetch", json={"rows": 100}).json()
    assert len(more["rows"]) == 15 and more["has_more"] is False
    assert client.post(q + "/cancel").status_code == 200
    assert client.delete(q).status_code == 204

    # monitoring (MON$ tables of the in-process engine)
    mon = client.get(base(sid, dbid) + "/monitor").json()
    assert mon["database"]["page_size"] == 8192 and mon["attachments"]


@requires_embedded
def test_local_backup_restore_and_maintenance(emb, tmp_path):
    client = emb
    sid, dbid = create_local(client, tmp_path / "src.fdb")
    execute(client, sid, dbid, "CREATE TABLE T (ID INTEGER PRIMARY KEY, S VARCHAR(20)); COMMIT; "
                               "INSERT INTO T SELECT FIRST 200 RDB$RELATION_ID + 1000 * 0 + ROW_NUMBER() OVER (), "
                               "'x' FROM RDB$RELATIONS CROSS JOIN RDB$TYPES;")
    count = client.get(base(sid, dbid) + "/tables/T/count").json()["count"]
    assert count == 200
    m = f"/api/servers/{sid}/databases/{dbid}/maintenance"

    # gbak on a file (server-side path = local path here) and restore as a new registration
    fbk = tmp_path / "src.fbk"
    wait_job(client, client.post(m + "/backup", json={"target": "server", "backup_file": str(fbk)}))
    assert fbk.stat().st_size > 1000
    target = tmp_path / "restored.fdb"
    j = wait_job(client, client.post(f"/api/servers/{sid}/maintenance/restore", json={
        "source": "server", "backup_file": str(fbk), "database_path": str(target), "register_as": "restored"}))
    assert any("gbak:" in line for line in j["log"])
    rid = next(d["id"] for d in client.get(f"/api/servers/{sid}").json()["databases"] if d["name"] == "restored")
    assert client.get(base(sid, rid) + "/tables/T/count").json()["count"] == 200

    # streamed backup (download through fbadmin) and upload-restore
    r = client.post(m + "/backup/stream", json={})
    assert r.status_code == 200, r.text
    with client.stream("GET", r.json()["url"]) as resp:
        data = b"".join(resp.iter_bytes())
    assert len(data) > 1000
    target2 = tmp_path / "uploaded.fdb"
    j = wait_job(client, client.post(f"/api/servers/{sid}/maintenance/restore/upload",
                                     params={"database_path": str(target2), "filename": "x.fbk"},
                                     content=data, headers={"Content-Type": "application/octet-stream"}))
    assert target2.is_file()

    # the older servers.py backup/restore endpoints (firebirdsql's service helpers)
    fbk2 = tmp_path / "old.fbk"
    wait_job(client, client.post(f"/api/servers/{sid}/backup", json={"database_id": dbid, "backup_file": str(fbk2)}))
    assert fbk2.is_file()

    # validation, sweep, statistics, header/properties
    wait_job(client, client.post(m + "/validate", json={"mode": "online"}))
    wait_job(client, client.post(m + "/sweep", json={}))
    wait_job(client, client.post(f"/api/servers/{sid}/databases/{dbid}/statistics"))
    props = client.get(m + "/properties").json()
    assert props["header"]["page_size"] == 16384 and props["engine_major"] == 5

    # not available on the embedded engine: a clear 400, not a crash
    r = client.get(f"/api/servers/{sid}/trace/sessions")
    assert r.status_code == 400 and "trace is not available" in r.json()["detail"].lower(), r.text
    r = client.post(f"/api/servers/{sid}/trace/sessions", json={"template": "slow_queries"})
    assert r.status_code == 400 and "embedded" in r.json()["detail"].lower(), r.text

    # drop the restored copy (DROP DATABASE through the native driver)
    client.post(f"/api/servers/{sid}/databases/{rid}/disconnect")
    assert client.post(f"/api/servers/{sid}/databases/{rid}/drop").status_code == 204
    assert not target.exists()


@requires_embedded
def test_open_existing_and_duplicates(emb, tmp_path):
    client = emb
    path = tmp_path / "a.fdb"
    sid, dbid = create_local(client, path)
    r = client.post("/api/embedded/databases", json={"path": str(path), "create": True})
    assert r.status_code == 400 and "already" in r.json()["detail"]
    r = client.post("/api/embedded/databases", json={"path": str(path)})
    assert r.status_code == 201 and r.json()["database"]["id"] == dbid and r.json()["created"] is False
    # unregister, then open the existing file again
    client.delete(f"/api/servers/{sid}/databases/{dbid}")
    r = client.post("/api/embedded/databases", json={"path": str(path), "name": "again"})
    assert r.status_code == 201, r.text
    assert r.json()["database"]["name"] == "again" and r.json()["server_id"] == sid
    # errors: missing file, not a database, remote-looking path
    r = client.post("/api/embedded/databases", json={"path": str(tmp_path / "missing.fdb")})
    assert r.status_code == 404
    junk = tmp_path / "junk.fdb"
    junk.write_bytes(b"not a database" * 100)
    r = client.post("/api/embedded/databases", json={"path": str(junk)})
    assert r.status_code == 400
    r = client.post("/api/embedded/databases", json={"path": "localhost:/tmp/x.fdb", "create": True})
    assert r.status_code == 400
    # the generic "create database" of the Local databases entry goes through the engine too
    r = client.post(f"/api/servers/{sid}/databases/create", json={"name": "b", "path": str(tmp_path / "b.fdb")})
    assert r.status_code == 201, r.text
    assert (tmp_path / "b.fdb").is_file()


@requires_embedded
def test_file_is_exclusive_to_the_process(emb, tmp_path):
    """SuperServer embedded opens the file exclusively: another process cannot attach meanwhile."""
    client = emb
    path = tmp_path / "x.fdb"
    sid, dbid = create_local(client, path)
    assert client.post(base(sid, dbid) + "/connect").status_code == 200  # keeps an attachment open
    lib = next(p for p in (Path(EMBEDDED_DIR) / "lib" / "libfbclient.so.2", Path(EMBEDDED_DIR) / "fbclient.dll",
                           Path(EMBEDDED_DIR) / "lib" / "libfbclient.dylib") if p.is_file())
    code = textwrap.dedent(f"""
        import os, sys
        os.environ["FIREBIRD"] = {EMBEDDED_DIR!r}
        from firebird.driver import driver_config, connect
        driver_config.fb_client_library.value = {str(lib)!r}
        cfg = driver_config.register_database("x")
        cfg.database.value = {str(path)!r}
        cfg.config.value = "Providers = Engine13"
        try:
            con = connect("x", user="SYSDBA")
        except Exception as exc:
            print("ERR", exc)
            sys.exit(3)
        print("OPENED", flush=True)
        if len(sys.argv) > 1:  # hold the attachment until stdin closes
            sys.stdin.read()
        con.close()
    """)
    env = {**os.environ, "FIREBIRD_LOCK": str(tmp_path / "otherlock")}
    p = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=120, env=env)
    assert p.returncode == 3, p.stdout + p.stderr
    # once fbadmin lets go, the other process can open it
    client.post(f"/api/servers/{sid}/databases/{dbid}/disconnect")
    deadline = time.time() + 30
    while True:
        p = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, timeout=120, env=env)
        if p.returncode == 0 or time.time() > deadline:
            break
        time.sleep(1)
    assert p.returncode == 0, p.stdout + p.stderr

    # ...and while another process holds it, fbadmin reports it as in use
    holder = subprocess.Popen([sys.executable, "-c", code, "hold"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                              text=True, env=env)
    try:
        assert holder.stdout.readline().startswith("OPENED")
        client.delete(f"/api/servers/{sid}/databases/{dbid}")
        r = client.post("/api/embedded/databases", json={"path": str(path)})
        assert r.status_code == 400 and "in use by another program" in r.json()["detail"], r.text
    finally:
        holder.communicate("", timeout=60)


def test_desktop_file_dialog_bridge(tmp_path):
    """window.pywebview.api.choose_database_file maps to pywebview's native file dialog."""
    from types import SimpleNamespace

    from fbadmin.desktop import DesktopApi

    calls = []

    class Win:
        def create_file_dialog(self, kind, **kw):
            calls.append((kind, kw))
            return str(tmp_path / "new.fdb") if kind == "save" else (str(tmp_path / "a.fdb"),)

    wv = SimpleNamespace(FileDialog=SimpleNamespace(OPEN="open", SAVE="save"), windows=[Win()])
    api = DesktopApi(wv)
    assert api.choose_database_file(True, str(tmp_path / "x.fdb")) == str(tmp_path / "new.fdb")
    assert calls[-1][1]["save_filename"] == "x.fdb" and calls[-1][1]["directory"] == str(tmp_path)
    assert api.choose_database_file(False, "") == str(tmp_path / "a.fdb")
    old = SimpleNamespace(OPEN_DIALOG=10, SAVE_DIALOG=30,
                          windows=[SimpleNamespace(create_file_dialog=lambda k, **kw: None)])
    assert DesktopApi(old).choose_database_file(False) is None

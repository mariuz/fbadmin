"""Local databases through the Firebird embedded engine (fbadmin/embedded.py).

The engine tests need an extracted embedded file set and ``firebird-driver``:

    scripts/embedded-test-setup.sh            # downloads Firebird 5 and extracts the file set
    FBADMIN_TEST_EMBEDDED_DIR=.cache/firebird-embedded/linux-x64 pytest tests/test_embedded.py

No Firebird server is used: every database is a file under the test's tmp_path.
"""

from __future__ import annotations

import os
import subprocess
import sys
import textwrap
import time
from pathlib import Path

import pytest

EMBEDDED_DIR = os.environ.get("FBADMIN_TEST_EMBEDDED_DIR", "")


def _why_not() -> str:
    if not EMBEDDED_DIR:
        return "FBADMIN_TEST_EMBEDDED_DIR is not set (see scripts/embedded-test-setup.sh)"
    if not Path(EMBEDDED_DIR).is_dir():
        return f"{EMBEDDED_DIR} does not exist"
    try:
        import firebird.driver  # noqa: F401
    except ImportError:
        return "firebird-driver is not installed"
    return ""


requires_embedded = pytest.mark.skipif(bool(_why_not()), reason=_why_not() or "ok")
pytestmark = pytest.mark.filterwarnings("ignore:Secondary attachment")


# ------------------------------------------------------------------ no engine needed
def test_check_local_path():
    from fbadmin.embedded import check_local_path

    assert check_local_path("/tmp/x/../a.fdb") == os.path.normpath("/tmp/a.fdb")
    for bad in ("", "a.fdb", "localhost:/db/a.fdb", "server/3050:/a.fdb", "inet://h/a.fdb", "xnet://a",
                "//host/share/a.fdb", "\\\\host\\share\\a.fdb", "employee"):
        with pytest.raises(ValueError):
            check_local_path(bad)


def test_unavailable_without_engine(client, monkeypatch, tmp_path):
    monkeypatch.setenv("FBADMIN_EMBEDDED_DIR", "")
    monkeypatch.delenv("FBADMIN_EMBEDDED_DIR")
    st = client.get("/api/embedded/status").json()
    if st["directory"]:  # a frozen build would find its bundled engine
        pytest.skip("an embedded engine is bundled")
    assert st["available"] is False and "FBADMIN_EMBEDDED_DIR" in st["reason"]
    r = client.post("/api/embedded/databases", json={"path": str(tmp_path / "a.fdb"), "create": True})
    assert r.status_code == 400 and "embedded" in r.json()["detail"].lower()


def test_turned_off(client, monkeypatch, tmp_path):
    monkeypatch.setenv("FBADMIN_EMBEDDED_DIR", str(tmp_path))
    monkeypatch.setenv("FBADMIN_EMBEDDED", "0")
    st = client.get("/api/embedded/status").json()
    assert st["available"] is False and "FBADMIN_EMBEDDED=0" in st["reason"]



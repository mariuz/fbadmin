-- Sample schema covering most object types; used by the DDL round-trip test.
CREATE DOMAIN D_MONEY AS NUMERIC(15,2) DEFAULT 0 NOT NULL CHECK (VALUE >= 0);
CREATE DOMAIN D_NAME AS VARCHAR(100) CHARACTER SET UTF8 COLLATE UNICODE_CI;
CREATE SEQUENCE SEQ_ORDERS START WITH 100 INCREMENT BY 5;
CREATE EXCEPTION E_INVALID 'Invalid value: @1';
CREATE ROLE R_READER;

CREATE TABLE CUSTOMER (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME D_NAME NOT NULL,
    EMAIL VARCHAR(200),
    BALANCE D_MONEY,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ACTIVE BOOLEAN DEFAULT TRUE,
    NOTES BLOB SUB_TYPE TEXT,
    "lower case" INTEGER,
    CONSTRAINT UQ_CUSTOMER_EMAIL UNIQUE (EMAIL)
);
COMMENT ON TABLE CUSTOMER IS 'Customers';
COMMENT ON COLUMN CUSTOMER.EMAIL IS 'Contact e-mail';

CREATE TABLE ORDERS (
    ID BIGINT NOT NULL,
    CUSTOMER_ID INTEGER NOT NULL,
    AMOUNT NUMERIC(18,4),
    QTY SMALLINT CHECK (QTY > 0),
    TOTAL COMPUTED BY (AMOUNT * QTY),
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (ID) ON DELETE CASCADE
);
CREATE DESCENDING INDEX IX_ORDERS_AMOUNT ON ORDERS (AMOUNT);
CREATE INDEX IX_ORDERS_EXPR ON ORDERS COMPUTED BY (AMOUNT * 2);

CREATE TRIGGER ORDERS_BI FOR ORDERS ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR SEQ_ORDERS;
END;

CREATE VIEW V_CUSTOMER_TOTALS (CUSTOMER_ID, NAME, TOTAL) AS
SELECT c.ID, c.NAME, SUM(o.AMOUNT) FROM CUSTOMER c LEFT JOIN ORDERS o ON o.CUSTOMER_ID = c.ID GROUP BY 1, 2;

CREATE PROCEDURE SP_ORDERS_FOR (CUST INTEGER, LIMIT_ROWS INTEGER = 10) RETURNS (ORDER_ID BIGINT, AMOUNT TYPE OF COLUMN ORDERS.AMOUNT) AS
DECLARE VARIABLE N INTEGER = 0;
BEGIN
  FOR SELECT ID, AMOUNT FROM ORDERS WHERE CUSTOMER_ID = :CUST INTO :ORDER_ID, :AMOUNT DO
  BEGIN
    N = N + 1;
    IF (N > LIMIT_ROWS) THEN EXIT;
    SUSPEND;
  END
END;

CREATE FUNCTION F_DOUBLE (X INTEGER) RETURNS INTEGER DETERMINISTIC AS
BEGIN
  RETURN X * 2;
END;

CREATE PACKAGE PK_UTIL AS
BEGIN
  FUNCTION ADD_ONE (X INTEGER) RETURNS INTEGER;
END;

CREATE PACKAGE BODY PK_UTIL AS
BEGIN
  FUNCTION ADD_ONE (X INTEGER) RETURNS INTEGER AS
  BEGIN
    RETURN X + 1;
  END
END;

GRANT R_READER TO PUBLIC;

-- Applied on top of complex_schema.sql to get a second, different schema for the diff tests.
CREATE DOMAIN D_EXTRA AS VARCHAR(5);
DROP DOMAIN D_UNUSED;
ALTER DOMAIN D_STATUS SET DEFAULT 'I';
ALTER DOMAIN D_EMAIL DROP CONSTRAINT;
ALTER DOMAIN D_EMAIL ADD CHECK (VALUE LIKE '%@%.%');
ALTER SEQUENCE SEQ_EMP INCREMENT BY 3;
CREATE SEQUENCE SEQ_EXTRA;
CREATE OR ALTER EXCEPTION E_FAIL 'Changed: @1';
DROP EXCEPTION E_UNUSED;
CREATE ROLE R_EXTRA;

ALTER TABLE EMP ADD EXTRA D_EXTRA DEFAULT 'x';
DROP INDEX IX_PROJECT_BUDGET;
ALTER TABLE PROJECT DROP ACTIVE;
CREATE INDEX IX_PROJECT_BUDGET ON PROJECT (BUDGET);
ALTER TABLE NO_PK ALTER B TYPE VARCHAR(40);
ALTER TABLE NO_PK ALTER A SET NOT NULL;
ALTER TABLE NO_PK ADD CONSTRAINT CK_NO_PK_A CHECK (A > 0);
ALTER TABLE EMP_PROJECT ALTER ROLE_NAME SET DEFAULT 'member';
ALTER TABLE DEPT DROP CONSTRAINT UQ_DEPT_NAME;
ALTER TABLE DEPT ADD CONSTRAINT UQ_DEPT_NAME UNIQUE (NAME, PARENT_ID);
CREATE TABLE EXTRA_T (ID INTEGER NOT NULL PRIMARY KEY, EMP_ID INTEGER REFERENCES EMP (ID), N COMPUTED BY (ID * 2));
DROP TABLE TMP_CALC;
CREATE INDEX IX_EXTRA_EMP ON EXTRA_T (EMP_ID, ID);

DROP TRIGGER V_EMP_BI;
SET TERM ^ ;
ALTER PROCEDURE SP_TOP_COUNT RETURNS (N INTEGER) AS BEGIN N = 0; SUSPEND; END^
SET TERM ; ^
DROP VIEW V_TREE;
DROP VIEW V_TOP;
DROP VIEW V_EMP_DEPT;
DROP VIEW V_EMP;
CREATE VIEW V_EMP (ID, EMAIL, PAY) AS SELECT ID, EMAIL, SALARY FROM EMP;
CREATE VIEW V_EMP_DEPT AS SELECT E.ID, E.EMAIL, E.PAY FROM V_EMP E;

SET TERM ^ ;
ALTER PROCEDURE SP_A (N INTEGER) RETURNS (R INTEGER) AS
BEGIN
  R = N * 2;
  SUSPEND;
END^
CREATE PROCEDURE SP_EXTRA (X INTEGER) RETURNS (Y INTEGER) AS
BEGIN
  SELECT COUNT(*) FROM V_EMP_DEPT WHERE ID = :X INTO :Y;
  SUSPEND;
END^
CREATE OR ALTER PACKAGE PK_HR AS
BEGIN
  FUNCTION RATE RETURNS NUMERIC(5,2);
  PROCEDURE RAISE_ALL (PCT INTEGER);
  FUNCTION HEADCOUNT RETURNS INTEGER;
END^
RECREATE PACKAGE BODY PK_HR AS
BEGIN
  FUNCTION RATE RETURNS NUMERIC(5,2) AS
  BEGIN
    RETURN 0.20;
  END
  PROCEDURE RAISE_ALL (PCT INTEGER) AS
  BEGIN
    UPDATE EMP SET SALARY = SALARY + :PCT;
  END
  FUNCTION HEADCOUNT RETURNS INTEGER AS
  BEGIN
    RETURN (SELECT COUNT(*) FROM EMP);
  END
END^
CREATE OR ALTER TRIGGER EMP_AU FOR EMP ACTIVE AFTER UPDATE POSITION 5 AS
BEGIN
  INSERT INTO AUDIT_LOG (ID, MSG) VALUES (OLD.ID, 'updated');
END^
CREATE TRIGGER EXTRA_T_BI FOR EXTRA_T BEFORE INSERT AS
BEGIN
  NEW.ID = COALESCE(NEW.ID, GEN_ID(SEQ_EXTRA, 1));
END^
SET TERM ; ^
DROP PROCEDURE SP_RAISE;

COMMENT ON TABLE EMP IS 'Staff';
COMMENT ON COLUMN EMP.SALARY IS NULL;
COMMENT ON TABLE EXTRA_T IS 'Extra table';
REVOKE UPDATE (EMAIL, STATUS) ON EMP FROM R_APP;
GRANT SELECT ON DEPT TO R_APP;
GRANT SELECT ON V_EMP_DEPT TO R_EXTRA;

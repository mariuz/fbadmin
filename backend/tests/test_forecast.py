"""Capacity and transaction-ID forecasting (roadmap 2.4): trends, severities, sequences against the columns they
feed (identity and trigger), table formats against 255, the space budget, and the capacity.forecast alert."""

from __future__ import annotations

import time

import pytest

from fbadmin.monitoring import forecast as F

from .conftest import requires_server
from .test_alerts import add_webhook, flush, receiver  # noqa: F401 - fixture

DAY = 86400.0


def test_trend_and_helpers():
    now = 1_800_000_000.0
    assert F.trend([(now, 10), (now + 3600, 20)]) is None  # less than 6 hours apart
    assert F.trend([(now, 10)]) is None
    assert F.trend([(now, 100), (now + DAY, 200), (now + 2 * DAY, 300)]) == pytest.approx(100)
    assert F.trend([(now, 300), (now + DAY, 200)]) == pytest.approx(-100)
    assert F.trend([(now, 5), (now + DAY, None), (now + 2 * DAY, 25)]) == pytest.approx(10)
    assert F._days_left(100, 1100, 100) == 10 and F._days_left(100, 1100, 0) is None and F._days_left(1, 2, None) is None
    assert F._severity(10, None) == "critical" and F._severity(100, None) == "warning" and F._severity(400, 10) == "ok"
    assert F._severity(None, 96) == "critical" and F._severity(None, 85) == "warning"
    assert F._fmt_days(0.5) == "less than a day" and F._fmt_days(45) == "45 days" and F._fmt_days(300) == "9 months"
    assert F._fmt_days(3650) == "9 years" and F._fmt_days(1e12) == "more than a million years"
    assert F._fmt_days(None) == "never at the current rate"


@requires_server
def test_forecast_of_a_database(client, database, receiver, monkeypatch):  # noqa: F811
    sid, dbid = database
    base = f"/api/servers/{sid}/databases/{dbid}"
    for sql in (
        "CREATE TABLE ITEMS (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(20))",
        "CREATE SEQUENCE SEQ_ORDERS",
        "CREATE TABLE ORDERS (ID INTEGER NOT NULL PRIMARY KEY, NOTE VARCHAR(20))",
        "CREATE TRIGGER ORDERS_BI FOR ORDERS BEFORE INSERT AS BEGIN IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR SEQ_ORDERS; END",
        "CREATE SEQUENCE SEQ_LOOSE",
        "ALTER SEQUENCE SEQ_ORDERS RESTART WITH 2000000000",
        "INSERT INTO ORDERS (NOTE) VALUES ('a')",
        "INSERT INTO ITEMS (NAME) VALUES ('x')",
    ):
        r = client.post(base + "/execute", json={"sql": sql})
        assert r.json()["error"] is None, (sql, r.json())
    for i in range(4):  # four formats for ITEMS
        client.post(base + "/execute", json={"sql": f"ALTER TABLE ITEMS ADD C{i} INTEGER"})

    # the first look records an observation; with one, there is no trend yet
    f = client.get(base + "/monitoring/forecast").json()
    assert f["observations"] == 1 and f["enough"] is False and f["tracked"] is False
    assert f["size"]["bytes"] > 0 and f["size"]["per_day"] is None
    assert f["transactions"]["limit"] == 2**48 - 1 and f["transactions"]["severity"] == "ok"
    seqs = {s["name"]: s for s in f["sequences"]}
    assert seqs["SEQ_ORDERS"]["value"] in (2000000000, 2000000001)  # Firebird 3: RESTART WITH sets the current value
    assert (seqs["SEQ_ORDERS"]["table"], seqs["SEQ_ORDERS"]["column"], seqs["SEQ_ORDERS"]["type"],
            seqs["SEQ_ORDERS"]["how"]) == ("ORDERS", "ID", "INTEGER", "trigger")
    assert seqs["SEQ_ORDERS"]["severity"] == "warning" and seqs["SEQ_ORDERS"]["pct"] == pytest.approx(93.13, abs=0.01)
    ident = next(s for s in f["sequences"] if s["how"] == "identity")
    assert (ident["table"], ident["column"], ident["type"]) == ("ITEMS", "ID", "INTEGER") and ident["value"] == 1
    assert seqs["SEQ_LOOSE"]["type"] == "BIGINT" and seqs["SEQ_LOOSE"]["table"] is None
    items_fmt = next(x for x in f["formats"] if x["table"] == "ITEMS")
    assert items_fmt["formats"] >= 5 and items_fmt["limit"] == 255 and items_fmt["severity"] == "ok"
    # within the hour, opening it again records nothing; "observe now" does
    assert client.get(base + "/monitoring/forecast").json()["observations"] == 1
    assert client.post(base + "/monitoring/forecast/observe").json()["observations"] == 2

    # history: two days ago the database was smaller and the sequence lower
    now = time.time()
    cur = F.observations(sid, dbid)[-1]
    old = {"pages": cur["pages"] - 20, "page_size": cur["page_size"], "next_tx": cur["next_tx"] - 2000,
           "seqs": {**cur["seqs"], "SEQ_ORDERS": 1_900_000_000}}
    F.add_observation(sid, dbid, old, ts=now - 2 * DAY)
    f = client.get(base + "/monitoring/forecast").json()
    assert f["enough"] is True and f["window_observations"] == 3
    assert f["size"]["per_day"] > 0 and f["size"]["in_90"] > f["size"]["bytes"]
    assert f["transactions"]["per_day"] > 0 and f["transactions"]["days_left"] > 365 * 1000
    so = next(s for s in f["sequences"] if s["name"] == "SEQ_ORDERS")
    assert so["per_day"] == pytest.approx(5e7, rel=0.05) and so["days_left"] < 5 and so["severity"] == "critical"
    assert f["sequences"][0]["name"] == "SEQ_ORDERS"  # the most urgent first
    assert any(x["key"] == "seq:SEQ_ORDERS" and x["severity"] == "critical" and "reaches it in" in x["title"]
               for x in f["findings"])

    # a space budget: the database is near it
    size = f["size"]["bytes"]
    assert client.put(base + "/monitoring/forecast/budget", json={"budget_bytes": int(size * 1.05)}).status_code == 200
    f = client.get(base + "/monitoring/forecast").json()
    assert f["size"]["budget_pct"] > 90 and f["size"]["severity"] == "critical"
    assert f["findings"][0]["severity"] == "critical"
    client.put(base + "/monitoring/forecast/budget", json={"budget_bytes": None})
    assert client.get(base + "/monitoring/forecast").json()["size"]["budget"] is None

    # formats: a lower limit makes ITEMS a finding
    monkeypatch.setattr(F, "FORMAT_LIMIT", 6)
    f = client.get(base + "/monitoring/forecast").json()
    assert any(x["key"] == "fmt:ITEMS" for x in f["findings"])

    # the alert: once per finding and severity
    hook = add_webhook(client, receiver)
    client.post("/api/alerts/rules", json={"name": "capacity", "event": "capacity.forecast", "server_id": sid,
                                           "database_id": dbid, "channels": [hook["id"]]})
    from fbadmin.api.deps import get_state

    with get_state().manager.meta(sid, dbid) as conn:
        raised = F.check_alerts(sid, dbid, F.analyze(sid, dbid, conn))
        again = F.check_alerts(sid, dbid, F.analyze(sid, dbid, conn))
        conn.rollback()
    assert "seq:SEQ_ORDERS" in raised and "fmt:ITEMS" in raised and again == []
    flush()
    titles = [receiver.json(i)["title"] for i in range(len(receiver.requests))]
    assert any(t.startswith("Sequence SEQ_ORDERS feeding ORDERS.ID (INTEGER)") for t in titles)
    for r in client.get("/api/alerts/rules").json():
        client.delete(f"/api/alerts/rules/{r['id']}")
    client.delete(f"/api/alerts/channels/{hook['id']}")

    # the history sampler records observations too
    client.put(base + "/monitoring/history/tracking", json={"enabled": True})
    F._last.clear()
    with F._store()._lock:
        F._store()._db.execute("UPDATE forecast_obs SET ts = ts - 7200 WHERE server_id = ? AND db_id = ?", (sid, dbid))
    n = F.observations(sid, dbid)
    client.post(base + "/monitoring/history/sample")
    assert len(F.observations(sid, dbid)) == len(n) + 1
    client.put(base + "/monitoring/history/tracking", json={"enabled": False})
    client.delete(base + "/monitoring/history")
    assert F.observations(sid, dbid) == []

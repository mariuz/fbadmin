-- A schema with dependency cycles, used by the schema tools tests (full extract round-trip, diff).
CREATE COLLATION UNICODE_NUM FOR UTF8 FROM UNICODE CASE INSENSITIVE 'NUMERIC-SORT=1';
CREATE DOMAIN D_ID AS INTEGER NOT NULL;
CREATE DOMAIN D_EMAIL AS VARCHAR(200) CHECK (VALUE IS NULL OR VALUE LIKE '%@%');
CREATE DOMAIN D_STATUS AS CHAR(1) DEFAULT 'A' NOT NULL CHECK (VALUE IN ('A', 'I'));
CREATE DOMAIN D_AMOUNT AS NUMERIC(15,2) DEFAULT 0 CHECK (VALUE >= 0);
CREATE DOMAIN D_UNUSED AS SMALLINT;
CREATE SEQUENCE SEQ_EMP START WITH 10 INCREMENT BY 2;
CREATE SEQUENCE SEQ_UNUSED;
ALTER SEQUENCE SEQ_EMP RESTART WITH 50;
CREATE EXCEPTION E_FAIL 'Operation failed: @1';
CREATE EXCEPTION E_UNUSED 'never raised';
CREATE ROLE R_APP;
CREATE ROLE R_ADMIN;

SET TERM ^ ;
CREATE PACKAGE PK_HR AS
BEGIN
  FUNCTION RATE RETURNS NUMERIC(5,2);
  PROCEDURE RAISE_ALL (PCT INTEGER);
END^

CREATE FUNCTION F_BONUS (SALARY NUMERIC(15,2)) RETURNS NUMERIC(15,2) AS
BEGIN
  RETURN SALARY * PK_HR.RATE();
END^
SET TERM ; ^

CREATE TABLE DEPT (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(50) NOT NULL COLLATE UNICODE_NUM,
    PARENT_ID INTEGER,
    MANAGER_ID INTEGER,
    CONSTRAINT UQ_DEPT_NAME UNIQUE (NAME)
);
CREATE TABLE EMP (
    ID D_ID,
    DEPT_ID INTEGER,
    EMAIL D_EMAIL,
    STATUS D_STATUS,
    SALARY D_AMOUNT,
    BONUS COMPUTED BY (F_BONUS(SALARY)),
    HIRED DATE DEFAULT CURRENT_DATE,
    NOTE BLOB SUB_TYPE TEXT,
    CONSTRAINT PK_EMP PRIMARY KEY (ID),
    CONSTRAINT FK_EMP_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPT (ID) ON DELETE SET NULL,
    CHECK (SALARY < 1000000)
);
ALTER TABLE DEPT ADD CONSTRAINT FK_DEPT_PARENT FOREIGN KEY (PARENT_ID) REFERENCES DEPT (ID);
ALTER TABLE DEPT ADD FOREIGN KEY (MANAGER_ID) REFERENCES EMP (ID);
CREATE TABLE PROJECT (
    ID BIGINT NOT NULL PRIMARY KEY,
    CODE CHAR(8) NOT NULL,
    LEAD_ID INTEGER REFERENCES EMP (ID),
    BUDGET DOUBLE PRECISION,
    ACTIVE BOOLEAN DEFAULT TRUE,
    CONSTRAINT UQ_PROJECT_CODE UNIQUE (CODE)
);
CREATE TABLE EMP_PROJECT (
    EMP_ID INTEGER NOT NULL,
    PROJECT_ID BIGINT NOT NULL,
    ROLE_NAME VARCHAR(30),
    PRIMARY KEY (EMP_ID, PROJECT_ID),
    FOREIGN KEY (EMP_ID) REFERENCES EMP (ID) ON DELETE CASCADE,
    FOREIGN KEY (PROJECT_ID) REFERENCES PROJECT (ID) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE NO_PK (A INTEGER, B VARCHAR(10));
CREATE GLOBAL TEMPORARY TABLE AUDIT_LOG (ID BIGINT, MSG VARCHAR(200)) ON COMMIT PRESERVE ROWS;
CREATE GLOBAL TEMPORARY TABLE TMP_CALC (X INTEGER) ON COMMIT DELETE ROWS;
CREATE DESCENDING INDEX IX_EMP_HIRED ON EMP (HIRED);
CREATE INDEX IX_EMP_EMAIL_UP ON EMP COMPUTED BY (UPPER(EMAIL));
CREATE INDEX IX_PROJECT_BUDGET ON PROJECT (BUDGET, ACTIVE);
ALTER INDEX IX_PROJECT_BUDGET INACTIVE;

SET TERM ^ ;
CREATE PROCEDURE SP_B (N INTEGER) RETURNS (R INTEGER) AS
BEGIN
  R = N;
  SUSPEND;
END^

CREATE PROCEDURE SP_A (N INTEGER) RETURNS (R INTEGER) AS
BEGIN
  IF (N <= 0) THEN R = 0;
  ELSE SELECT R FROM SP_B(:N - 1) INTO :R;
  SUSPEND;
END^

ALTER PROCEDURE SP_B (N INTEGER) RETURNS (R INTEGER) AS
BEGIN
  IF (N <= 0) THEN R = 0;
  ELSE SELECT R + 1 FROM SP_A(:N - 1) INTO :R;
  SUSPEND;
END^

CREATE PROCEDURE SP_TREE (ROOT INTEGER = NULL) RETURNS (ID INTEGER, NAME TYPE OF COLUMN DEPT.NAME, LVL INTEGER) AS
BEGIN
  FOR WITH RECURSIVE T AS (
      SELECT ID, NAME, 0 AS LVL FROM DEPT WHERE (PARENT_ID IS NULL AND :ROOT IS NULL) OR ID = :ROOT
      UNION ALL
      SELECT D.ID, D.NAME, T.LVL + 1 FROM DEPT D JOIN T ON D.PARENT_ID = T.ID)
    SELECT ID, NAME, LVL FROM T INTO :ID, :NAME, :LVL
  DO SUSPEND;
END^

CREATE PROCEDURE SP_RAISE (MSG VARCHAR(100)) AS
BEGIN
  EXCEPTION E_FAIL USING (MSG);
END^

CREATE PACKAGE BODY PK_HR AS
BEGIN
  FUNCTION RATE RETURNS NUMERIC(5,2) AS
  BEGIN
    RETURN 0.10;
  END
  PROCEDURE RAISE_ALL (PCT INTEGER) AS
  DECLARE R INTEGER;
  BEGIN
    UPDATE EMP SET SALARY = SALARY * (100 + :PCT) / 100;
    SELECT R FROM SP_A(1) INTO :R;
  END
END^
SET TERM ; ^

CREATE VIEW V_EMP (ID, DEPT_ID, EMAIL, PAY) AS
SELECT ID, DEPT_ID, EMAIL, SALARY + COALESCE(BONUS, 0) FROM EMP WHERE STATUS = 'A';
CREATE VIEW V_EMP_DEPT AS
SELECT E.ID, E.EMAIL, E.PAY, D.NAME AS DEPT_NAME FROM V_EMP E JOIN DEPT D ON D.ID = E.DEPT_ID;
CREATE VIEW V_TOP AS
SELECT FIRST 10 * FROM V_EMP_DEPT ORDER BY PAY DESC;
CREATE VIEW V_TREE AS
SELECT T.ID, T.NAME, T.LVL FROM SP_TREE(NULL) T;

SET TERM ^ ;
CREATE PROCEDURE SP_TOP_COUNT RETURNS (N INTEGER) AS
BEGIN
  SELECT COUNT(*) FROM V_TOP INTO :N;
  SUSPEND;
END^

CREATE TRIGGER EMP_BI FOR EMP ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR SEQ_EMP;
  IF (NEW.SALARY > 999999) THEN EXCEPTION E_FAIL USING ('salary');
END^

CREATE TRIGGER EMP_AU FOR EMP INACTIVE AFTER UPDATE OR DELETE POSITION 5 AS
BEGIN
  INSERT INTO AUDIT_LOG (ID, MSG) VALUES (OLD.ID, 'changed');
END^

CREATE TRIGGER V_EMP_BI FOR V_EMP ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  INSERT INTO EMP (ID, DEPT_ID, EMAIL) VALUES (NEW.ID, NEW.DEPT_ID, NEW.EMAIL);
END^

CREATE TRIGGER TR_CONNECT ACTIVE ON CONNECT POSITION 0 AS
BEGIN
  RDB$SET_CONTEXT('USER_SESSION', 'FBADMIN_TEST', '1');
END^
SET TERM ; ^

